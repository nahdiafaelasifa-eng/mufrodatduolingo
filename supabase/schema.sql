-- Jalankan seluruh SQL ini di Supabase SQL Editor.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  total_xp integer not null default 0,
  current_streak integer not null default 0,
  created_at timestamptz not null default now()
);
create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  name_ar text,
  description text
);
create table if not exists public.vocabularies (
  id bigint generated by default as identity primary key,
  category_id bigint references public.categories(id) on delete set null,
  arabic text not null,
  transliteration text,
  meaning text not null,
  part_of_speech text,
  example_ar text,
  example_id text,
  audio_url text,
  created_at timestamptz not null default now()
);
create table if not exists public.user_progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  vocabulary_id bigint not null references public.vocabularies(id) on delete cascade,
  mastery integer not null default 0 check (mastery between 0 and 5),
  last_reviewed_at timestamptz,
  unique(user_id, vocabulary_id)
);
create table if not exists public.quiz_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  score integer not null default 0,
  total_questions integer not null default 0,
  created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
alter table public.user_progress enable row level security;
alter table public.quiz_attempts enable row level security;
alter table public.categories enable row level security;
alter table public.vocabularies enable row level security;
create policy "Profiles are readable by owner" on public.profiles for select using (auth.uid() = id);
create policy "Profiles can be updated by owner" on public.profiles for update using (auth.uid() = id);
create policy "Users can read own progress" on public.user_progress for select using (auth.uid() = user_id);
create policy "Users can manage own progress" on public.user_progress for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users can read own attempts" on public.quiz_attempts for select using (auth.uid() = user_id);
create policy "Users can insert own attempts" on public.quiz_attempts for insert with check (auth.uid() = user_id);
create policy "Categories are public read" on public.categories for select using (true);
create policy "Vocabulary is public read" on public.vocabularies for select using (true);
-- Buat profil otomatis setelah user mendaftar.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'display_name', 'Pelajar'));
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();
